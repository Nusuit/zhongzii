interface LangContextValue {
  lang: Lang;
  t: (key: string) => string;
  setLang: (lang: Lang) => void;
}

export const LangContext = createContext<LangContextValue>({
  lang: "vi",
  t: (k) => k,
  setLang: () => {},
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("vi");

  useEffect(() => {
    const saved = localStorage.getItem("xh-lang") as Lang | null;
    if (saved && (saved === "vi" || saved === "en" || saved === "zh")) {
      setLangState(saved);
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("xh-lang", l);
    document.documentElement.setAttribute("lang", l);
  }, []);

  const t = useCallback(
    (key: string): string => {
      const dict = I18N_DICT[lang] ?? I18N_DICT.vi;
      return dict[key] ?? I18N_DICT.vi[key] ?? key;
    },
    [lang]
  );

  return <LangContext.Provider value={{ lang, t, setLang }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

export { I18N_DICT };
export type { Lang };
